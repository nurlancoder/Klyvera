#!/usr/bin/env python3
"""Generate Klyvera theme artifacts from design/tokens.json.

Outputs:
  shell/styles/Theme.qml
  shell/styles/qmldir
  web/src/styles/tokens.css
  docs/contrast-report.md

Run without arguments to write, or with --check to verify that the committed
files match the tokens and that required contrast pairs still pass.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
TOKENS_PATH = ROOT / "design" / "tokens.json"

THEME_QML = ROOT / "shell" / "styles" / "Theme.qml"
QMLDIR = ROOT / "shell" / "styles" / "qmldir"
TOKENS_CSS = ROOT / "web" / "src" / "styles" / "tokens.css"
CONTRAST_DOC = ROOT / "docs" / "contrast-report.md"

GENERATED_NOTE = (
    "Generated by design/generators/generate.py from design/tokens.json. "
    "Do not edit by hand."
)

REQUIRED_TOP_LEVEL = [
    "version",
    "themes",
    "spacing",
    "radius",
    "borders",
    "elevation",
    "typography",
    "motion",
    "icon",
    "layout",
    "accessibility",
]

REQUIRED_COLORS = [
    "background",
    "surface",
    "surfaceRaised",
    "surfaceHover",
    "surfaceActive",
    "surfaceSunken",
    "overlay",
    "textPrimary",
    "textSecondary",
    "textDisabled",
    "accentPurple",
    "accentBlue",
    "accentMint",
    "success",
    "danger",
    "warning",
    "info",
    "onAccent",
    "borderSubtle",
    "borderStrong",
    "focusRing",
    "selection",
    "shadow",
]

TEXT_FOREGROUNDS = [
    "textPrimary",
    "textSecondary",
    "accentPurple",
    "accentBlue",
    "accentMint",
    "success",
    "danger",
    "warning",
    "info",
]
TEXT_BACKGROUNDS = ["background", "surface", "surfaceRaised", "surfaceHover"]
ON_ACCENTS = [
    "accentPurple",
    "accentBlue",
    "accentMint",
    "success",
    "danger",
    "warning",
    "info",
]
FOCUS_BACKGROUNDS = ["background", "surface", "surfaceRaised", "surfaceHover"]

NORMAL_TEXT_MIN = 4.5
UI_COMPONENT_MIN = 3.0


def fail(message: str) -> None:
    print(f"error: {message}", file=sys.stderr)
    raise SystemExit(1)


def load_tokens() -> dict[str, Any]:
    try:
        with TOKENS_PATH.open(encoding="utf-8") as handle:
            tokens = json.load(handle)
    except FileNotFoundError:
        fail(f"missing {TOKENS_PATH}")
    except json.JSONDecodeError as error:
        fail(f"invalid JSON in {TOKENS_PATH}: {error}")

    missing = [key for key in REQUIRED_TOP_LEVEL if key not in tokens]
    if missing:
        fail(f"tokens.json is missing top-level keys: {', '.join(missing)}")
    if not tokens["themes"]:
        fail("tokens.json defines no themes")
    for name, theme in tokens["themes"].items():
        colors = theme.get("colors", {})
        absent = [key for key in REQUIRED_COLORS if key not in colors]
        if absent:
            fail(f"theme '{name}' is missing colors: {', '.join(absent)}")
        if theme.get("colorScheme") not in {"dark", "light"}:
            fail(f"theme '{name}' needs colorScheme 'dark' or 'light'")
    return tokens


def parse_color(value: Any) -> tuple[str, float]:
    if isinstance(value, str):
        hex_value = value
        alpha = 1.0
    elif isinstance(value, dict) and "hex" in value and "alpha" in value:
        hex_value = str(value["hex"])
        alpha = float(value["alpha"])
    else:
        fail(f"unsupported color value: {value!r}")

    hex_value = hex_value.strip()
    if not hex_value.startswith("#") or len(hex_value) != 7:
        fail(f"color must be #RRGGBB: {value!r}")
    int(hex_value[1:], 16)
    if not 0.0 <= alpha <= 1.0:
        fail(f"color alpha must be between 0 and 1: {value!r}")
    return hex_value.upper(), alpha


def to_qml(value: Any) -> str:
    hex_value, alpha = parse_color(value)
    if alpha >= 1.0:
        return hex_value
    return f"#{round(alpha * 255):02X}{hex_value[1:]}"


def to_css(value: Any) -> str:
    hex_value, alpha = parse_color(value)
    if alpha >= 1.0:
        return hex_value.lower()
    red = int(hex_value[1:3], 16)
    green = int(hex_value[3:5], 16)
    blue = int(hex_value[5:7], 16)
    return f"rgba({red}, {green}, {blue}, {alpha:g})"


def kebab(name: str) -> str:
    return "".join(
        "-" + character.lower() if character.isupper() else character
        for character in name
    )


def rgb(value: Any) -> tuple[float, float, float]:
    hex_value, alpha = parse_color(value)
    if alpha < 1.0:
        fail(f"contrast checks require opaque colors, got {value!r}")
    return (
        int(hex_value[1:3], 16) / 255.0,
        int(hex_value[3:5], 16) / 255.0,
        int(hex_value[5:7], 16) / 255.0,
    )


def relative_luminance(value: Any) -> float:
    def linear(channel: float) -> float:
        return channel / 12.92 if channel <= 0.04045 else ((channel + 0.055) / 1.055) ** 2.4

    red, green, blue = (linear(channel) for channel in rgb(value))
    return 0.2126 * red + 0.7152 * green + 0.0722 * blue


def contrast_ratio(foreground: Any, background: Any) -> float:
    first = relative_luminance(foreground)
    second = relative_luminance(background)
    lighter, darker = max(first, second), min(first, second)
    return (lighter + 0.05) / (darker + 0.05)


def build_theme_qml(tokens: dict[str, Any]) -> str:
    lines: list[str] = [
        "// " + GENERATED_NOTE,
        "// Switch appearance by setting Theme.themeName, Theme.scale and",
        "// Theme.reduceMotion from the integration layer. Components must use",
        "// scaled()/scaledInt() and the layout class helpers, never raw pixels.",
        "pragma Singleton",
        "import QtQuick",
        "",
        "QtObject {",
        "    id: theme",
        "",
        f'    readonly property string productName: "{tokens["name"]}"',
        f'    readonly property string tokenVersion: "{tokens["version"]}"',
        "    readonly property var availableThemes: ["
        + ", ".join(f'"{name}"' for name in tokens["themes"])
        + "]",
        "",
        "    property string themeName: \"dark\"",
        "    property real scale: 1.0",
        "    property bool reduceMotion: false",
        "",
        "    readonly property var palettes: ({",
    ]

    theme_items = list(tokens["themes"].items())
    for index, (name, theme) in enumerate(theme_items):
        lines.append(f'        "{name}": {{')
        color_items = list(theme["colors"].items())
        for color_index, (color_name, value) in enumerate(color_items):
            comma = "," if color_index < len(color_items) - 1 else ""
            lines.append(f'            "{color_name}": "{to_qml(value)}"{comma}')
        suffix = "," if index < len(theme_items) - 1 else ""
        lines.append(f"        }}{suffix}")
    lines.extend(
        [
            "    })",
            "    readonly property var palette: palettes[themeName]"
            ' ? palettes[themeName] : palettes["dark"]',
            "",
        ]
    )

    first_theme = next(iter(tokens["themes"].values()))
    for color_name in first_theme["colors"]:
        lines.append(
            f"    readonly property color {color_name}: palette.{color_name}"
        )

    lines.extend(["", "    readonly property QtObject spacing: QtObject {"])
    for name, value in tokens["spacing"].items():
        lines.append(f"        readonly property real {name}: {value}")
    lines.append("    }")

    lines.extend(["", "    readonly property QtObject radius: QtObject {"])
    for name, value in tokens["radius"].items():
        lines.append(f"        readonly property real {name}: {value}")
    lines.append("    }")

    lines.extend(["", "    readonly property QtObject borders: QtObject {"])
    for name, value in tokens["borders"].items():
        lines.append(f"        readonly property real {name}: {value}")
    lines.append("    }")

    lines.extend(["", "    readonly property QtObject elevation: QtObject {"])
    for name, value in tokens["elevation"].items():
        lines.append(f"        readonly property QtObject {name}: QtObject {{")
        lines.append(f"            readonly property real y: {value['y']}")
        lines.append(f"            readonly property real blur: {value['blur']}")
        lines.append(f"            readonly property real spread: {value['spread']}")
        lines.append(f"            readonly property real opacity: {value['opacity']}")
        lines.append("        }")
    lines.append("    }")

    typography = tokens["typography"]
    lines.extend(["", "    readonly property QtObject typography: QtObject {"])
    for role, family in typography["families"].items():
        lines.append(
            f'        readonly property string {role}Family: "{family["name"]}"'
        )
        lines.append(
            f'        readonly property string {role}Stack: "{family["stack"]}"'
        )
    for name, value in typography["weights"].items():
        lines.append(f"        readonly property int weight{kebab(name).title().replace('-', '')}: {value}")
    for name, value in typography["scale"].items():
        lines.append(f"        readonly property QtObject {name}: QtObject {{")
        lines.append(f"            readonly property int size: {value['size']}")
        lines.append(f"            readonly property int lineHeight: {value['lineHeight']}")
        lines.append(f"            readonly property int weight: {value['weight']}")
        lines.append(
            f"            readonly property real letterSpacing: {value['letterSpacing']}"
        )
        lines.append("        }")
    lines.append("    }")

    motion = tokens["motion"]
    lines.extend(
        [
            "",
            "    readonly property QtObject motion: QtObject {",
            f"        readonly property bool reduceMotionDefault: "
            f"{str(motion['reduceMotionDefault']).lower()}",
        ]
    )
    for name, value in motion["durations"].items():
        lines.append(f"        readonly property int duration{name.capitalize()}: {value}")
    for name, values in motion["easings"].items():
        joined = ", ".join(str(item) for item in values)
        lines.append(f"        readonly property var easing{name.capitalize()}: [{joined}]")
    lines.append("    }")

    icon = tokens["icon"]
    lines.extend(
        [
            "",
            "    readonly property QtObject icon: QtObject {",
            f'        readonly property string set: "{icon["set"]}"',
            f'        readonly property string license: "{icon["license"]}"',
            f"        readonly property real strokeWidth: {icon['strokeWidth']}",
            "        readonly property QtObject sizes: QtObject {",
        ]
    )
    for name, value in icon["sizes"].items():
        lines.append(f"            readonly property real {name}: {value}")
    lines.extend(["        }", "    }"])

    layout = tokens["layout"]
    lines.extend(["", "    readonly property QtObject layout: QtObject {"])
    lines.append("        readonly property QtObject breakpoints: QtObject {")
    for name, value in layout["breakpoints"].items():
        lines.append(f"            readonly property int {name}: {value}")
    lines.append("        }")
    for group_name in ("panel", "launcher", "controlCenter", "spaces"):
        lines.append(f"        readonly property QtObject {group_name}: QtObject {{")
        for name, value in layout[group_name].items():
            lines.append(f"            readonly property real {name}: {value}")
        lines.append("        }")
    lines.append("    }")

    accessibility = tokens["accessibility"]
    lines.extend(["", "    readonly property QtObject accessibility: QtObject {"])
    for name, value in accessibility.items():
        lines.append(f"        readonly property real {name}: {value}")
    lines.append("    }")

    breakpoints = layout["breakpoints"]
    lines.extend(
        [
            "",
            "    function scaled(value) {",
            "        return Math.round(value * scale * 100) / 100",
            "    }",
            "",
            "    function scaledInt(value) {",
            "        return Math.round(value * scale)",
            "    }",
            "",
            "    function motionDuration(base) {",
            "        return reduceMotion ? 0 : base",
            "    }",
            "",
            "    function layoutClass(width) {",
            f'        if (width <= {breakpoints["compactMax"]}) return "compact"',
            f'        if (width <= {breakpoints["regularMax"]}) return "regular"',
            f'        if (width <= {breakpoints["wideMax"]}) return "wide"',
            '        return "ultrawide"',
            "    }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def build_qmldir() -> str:
    return "module Klyvera.Styles\nsingleton Theme 1.0 Theme.qml\n"


def build_tokens_css(tokens: dict[str, Any]) -> str:
    lines = [
        "/* " + GENERATED_NOTE + " */",
        "",
        ":root {",
        "  --klyvera-scale: 1;",
    ]

    for name, value in tokens["spacing"].items():
        lines.append(f"  --klyvera-space-{name}: {value}px;")
    lines.append("")
    for name, value in tokens["radius"].items():
        lines.append(f"  --klyvera-radius-{name}: {value}px;")
    lines.append("")
    for name, value in tokens["borders"].items():
        lines.append(f"  --klyvera-border-{name}: {value}px;")

    typography = tokens["typography"]
    lines.append("")
    for role, family in typography["families"].items():
        lines.append(f"  --klyvera-font-{role}: {family['stack']};")
    for name, value in typography["weights"].items():
        lines.append(f"  --klyvera-weight-{name}: {value};")
    for name, value in typography["scale"].items():
        lines.append(f"  --klyvera-text-{kebab(name)}-size: {value['size']}px;")
        lines.append(
            f"  --klyvera-text-{kebab(name)}-line-height: {value['lineHeight']}px;"
        )
        lines.append(f"  --klyvera-text-{kebab(name)}-weight: {value['weight']};")
        lines.append(
            f"  --klyvera-text-{kebab(name)}-letter-spacing: "
            f"{value['letterSpacing']}px;"
        )

    motion = tokens["motion"]
    lines.append("")
    for name, value in motion["durations"].items():
        lines.append(f"  --klyvera-duration-{name}: {value}ms;")
    for name, values in motion["easings"].items():
        joined = ", ".join(f"{item:g}" for item in values)
        lines.append(f"  --klyvera-ease-{name}: cubic-bezier({joined});")

    icon = tokens["icon"]
    lines.append("")
    lines.append(f'  --klyvera-icon-set: "{icon["set"]}";')
    lines.append(f"  --klyvera-icon-stroke: {icon['strokeWidth']};")
    for name, value in icon["sizes"].items():
        lines.append(f"  --klyvera-icon-size-{name}: {value}px;")

    layout = tokens["layout"]
    lines.append("")
    for name, value in layout["breakpoints"].items():
        lines.append(f"  --klyvera-layout-{kebab(name)}: {value}px;")
    for group_name in ("panel", "launcher", "controlCenter", "spaces"):
        for name, value in layout[group_name].items():
            unit = "" if "ratio" in name.lower() else "px"
            lines.append(
                f"  --klyvera-{kebab(group_name)}-{kebab(name)}: {value}{unit};"
            )

    accessibility = tokens["accessibility"]
    lines.append("")
    for name, value in accessibility.items():
        lines.append(f"  --klyvera-a11y-{kebab(name)}: {value}px;")

    lines.append("}")
    lines.append("")

    theme_items = list(tokens["themes"].items())
    for index, (name, theme) in enumerate(theme_items):
        if index == 0:
            selector = ':root,\n[data-theme="dark"]'
        else:
            selector = f'[data-theme="{kebab(name)}"]'
        lines.append(selector + " {")
        lines.append(f"  color-scheme: {theme['colorScheme']};")
        for color_name, value in theme["colors"].items():
            lines.append(
                f"  --klyvera-color-{kebab(color_name)}: {to_css(value)};"
            )
        for elevation_name, value in tokens["elevation"].items():
            if float(value["opacity"]) == 0.0:
                shadow = "none"
            else:
                shadow_color = to_css(theme["colors"]["shadow"])
                if shadow_color.startswith("#"):
                    red = int(shadow_color[1:3], 16)
                    green = int(shadow_color[3:5], 16)
                    blue = int(shadow_color[5:7], 16)
                    shadow_color = (
                        f"rgba({red}, {green}, {blue}, {value['opacity']:g})"
                    )
                shadow = (
                    f"{value['y']}px {value['blur']}px {value['spread']}px "
                    f"{shadow_color}"
                )
            lines.append(f"  --klyvera-elevation-{kebab(elevation_name)}: {shadow};")
        lines.append("}")
        lines.append("")

    lines.extend(
        [
            "@media (prefers-reduced-motion: reduce) {",
            "  :root {",
            "    --klyvera-duration-instant: 0ms;",
            "    --klyvera-duration-fast: 0ms;",
            "    --klyvera-duration-normal: 0ms;",
            "    --klyvera-duration-slow: 0ms;",
            "  }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def contrast_rows(theme_name: str, theme: dict[str, Any]) -> tuple[list[tuple[str, str, str, str, str, bool]], list[tuple[str, str, str, str, str, bool]], list[tuple[str, str, str, str, str, bool]]]:
    colors = theme["colors"]
    required: list[tuple[str, str, str, str, str, bool]] = []
    informational: list[tuple[str, str, str, str, str, bool]] = []

    for foreground in TEXT_FOREGROUNDS:
        for background in TEXT_BACKGROUNDS:
            ratio = contrast_ratio(colors[foreground], colors[background])
            required.append(
                (
                    foreground,
                    background,
                    parse_color(colors[foreground])[0],
                    parse_color(colors[background])[0],
                    f"{ratio:.2f}:1",
                    ratio >= NORMAL_TEXT_MIN,
                )
            )

    for accent in ON_ACCENTS:
        ratio = contrast_ratio(colors["onAccent"], colors[accent])
        required.append(
            (
                "onAccent",
                accent,
                parse_color(colors["onAccent"])[0],
                parse_color(colors[accent])[0],
                f"{ratio:.2f}:1",
                ratio >= NORMAL_TEXT_MIN,
            )
        )

    for background in FOCUS_BACKGROUNDS:
        ratio = contrast_ratio(colors["focusRing"], colors[background])
        required.append(
            (
                "focusRing",
                background,
                parse_color(colors["focusRing"])[0],
                parse_color(colors[background])[0],
                f"{ratio:.2f}:1",
                ratio >= UI_COMPONENT_MIN,
            )
        )

    for background in ("background", "surface"):
        ratio = contrast_ratio(colors["textDisabled"], colors[background])
        informational.append(
            (
                "textDisabled",
                background,
                parse_color(colors["textDisabled"])[0],
                parse_color(colors[background])[0],
                f"{ratio:.2f}:1",
                ratio >= NORMAL_TEXT_MIN,
            )
        )

    return required, informational


def build_contrast_report(tokens: dict[str, Any]) -> tuple[str, int]:
    lines = [
        "# Contrast report",
        "",
        "Generated from `design/tokens.json` by "
        "`design/generators/generate.py`. Do not edit by hand.",
        "",
        "## Method",
        "",
        "- Ratios use the WCAG 2.1 relative-luminance formula with sRGB channel",
        "  linearisation.",
        "- Normal text requires **4.5:1** (WCAG AA). Klyvera applies this to all",
        "  body, label and caption text, not only to 16 px text.",
        "- The focus ring is a non-text UI indicator and requires **3:1** against",
        "  adjacent surfaces (WCAG 1.4.11).",
        "- Disabled text is exempt from contrast requirements; its ratios are",
        "  listed for information only.",
        "- Borders are supplementary: Klyvera never relies on a low-contrast border",
        "  as the only affordance, so border pairs are not enforced here.",
        "",
    ]
    failures = 0
    for theme_name, theme in tokens["themes"].items():
        required, informational = contrast_rows(theme_name, theme)
        theme_failures = sum(1 for row in required if not row[5])
        failures += theme_failures
        lines.extend(
            [
                f"## {theme['label']} (`{theme_name}`)",
                "",
                f"Required pairs: {len(required)}. Failures: {theme_failures}.",
                "",
                "| Foreground | Background | Foreground hex | Background hex | Ratio | Result |",
                "| --- | --- | --- | --- | --- | --- |",
            ]
        )
        for foreground, background, fg_hex, bg_hex, ratio, passed in required:
            lines.append(
                f"| `{foreground}` | `{background}` | `{fg_hex}` | `{bg_hex}` | "
                f"{ratio} | {'PASS' if passed else 'FAIL'} |"
            )
        lines.extend(
            [
                "",
                "Disabled text (informational, WCAG-exempt):",
                "",
                "| Foreground | Background | Ratio | Result |",
                "| --- | --- | --- | --- |",
            ]
        )
        for foreground, background, _fg_hex, _bg_hex, ratio, passed in informational:
            lines.append(
                f"| `{foreground}` | `{background}` | {ratio} | "
                f"{'PASS' if passed else 'EXEMPT'} |"
            )
        lines.append("")

    if failures:
        lines.extend(
            [
                "## Summary",
                "",
                f"**{failures} required pair(s) fail WCAG AA.** Fix the palette in",
                "`design/tokens.json` before regenerating.",
                "",
            ]
        )
    else:
        lines.extend(
            [
                "## Summary",
                "",
                "All required text and focus-indicator pairs pass WCAG AA in all",
                "three themes. See the tables above for measured ratios.",
                "",
            ]
        )
    return "\n".join(lines), failures


def build_outputs(tokens: dict[str, Any]) -> dict[Path, str]:
    contrast_report, _failures = build_contrast_report(tokens)
    return {
        THEME_QML: build_theme_qml(tokens),
        QMLDIR: build_qmldir(),
        TOKENS_CSS: build_tokens_css(tokens),
        CONTRAST_DOC: contrast_report,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify generated files are current instead of writing them",
    )
    args = parser.parse_args()

    tokens = load_tokens()
    outputs = build_outputs(tokens)
    _report, failures = build_contrast_report(tokens)

    if failures:
        print(
            f"error: {failures} contrast pair(s) fail WCAG AA; see docs/contrast-report.md",
            file=sys.stderr,
        )

    if args.check:
        stale: list[Path] = []
        for path, content in outputs.items():
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path)
        if stale:
            for path in stale:
                print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
            print(
                "run: python3 design/generators/generate.py",
                file=sys.stderr,
            )
            return 1
        if failures:
            return 1
        print(f"generated files are in sync ({len(outputs)} files)")
        return 0

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")

    if failures:
        return 1
    print("contrast: all required pairs pass WCAG AA")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
